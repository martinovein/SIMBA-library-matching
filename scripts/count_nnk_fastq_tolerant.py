def parse_args(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--workbook',type=Path,default=Path('library-description.xlsx')); p.add_argument('--data-dir',type=Path,default=Path('data')); p.add_argument('--output-dir',type=Path,default=Path('outputs/nnk_counting_tolerant'))
    p.add_argument('--threads',type=int,default=1); p.add_argument('--min-base-quality',type=int,default=20); p.add_argument('--min-mean-quality',type=float,default=None); p.add_argument('--max-n',type=int,default=0)
    p.add_argument('--max-5prime-anchor-mismatches',type=int,default=0); p.add_argument('--max-3prime-anchor-mismatches',type=int,default=0); p.add_argument('--max-reads-per-file',type=int,default=None)
    p.add_argument('--force',action='store_true'); p.add_argument('--dry-run',action='store_true')
