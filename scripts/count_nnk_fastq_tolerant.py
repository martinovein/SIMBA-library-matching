def main(argv=None):
    args=parse_args(argv); out=args.output_dir
    if out.exists() and any(out.iterdir()) and not args.force:
        print(f"Output directory {out} exists and is non-empty; pass --force", file=sys.stderr); return 2
    if out.exists() and args.force: shutil.rmtree(out)
    out.mkdir(parents=True, exist_ok=True)
    logging.basicConfig(level=logging.INFO, format='%(asctime)s %(levelname)s %(message)s', handlers=[logging.FileHandler(out/'pipeline.log','w'), logging.StreamHandler(sys.stderr)])
    workbook_sha=base.sha256_file(args.workbook)
