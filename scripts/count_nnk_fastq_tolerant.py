@dataclass(frozen=True)
class AnchorHit:
    start: int
    mismatches: int
    positions: tuple[int, ...]
    qualities: tuple[int, ...]


@dataclass(frozen=True)
class TolerantExtraction:
    coding: str
    coding_qual: str
    orientation: str
    anchor5_mismatches: int
    anchor3_mismatches: int
    anchor5_positions: tuple[int, ...]
    anchor3_positions: tuple[int, ...]
    anchor5_qualities: tuple[int, ...]
    anchor3_qualities: tuple[int, ...]
    tolerant: bool
    reason: str = ""
    invalid_insert_lengths: tuple[int, ...] = ()


def atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=path.name, suffix=".tmp", dir=path.parent)
    with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)
    os.replace(tmp, path)


def atomic_write_rows(path: Path, rows: list[dict[str, Any]], fieldnames: list[str], delimiter: str = ",") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=path.name, suffix=".tmp", dir=path.parent)
    with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fieldnames, delimiter=delimiter, extrasaction="ignore")
        w.writeheader(); w.writerows(rows)
    os.replace(tmp, path)


def hamming_anchor_hits(seq: str, qual: str, anchor: str, max_mismatches: int) -> list[AnchorHit]:
    hits: list[AnchorHit] = []
    if len(seq) < len(anchor):
        return hits
    for start in range(0, len(seq) - len(anchor) + 1):
        mm_pos = []
        mm_qual = []
        mm = 0
        for i, expected in enumerate(anchor):
            if seq[start + i] != expected:
                mm += 1
                if mm > max_mismatches:
                    break
                mm_pos.append(i + 1)
                mm_qual.append(ord(qual[start + i]) - 33)
        if mm <= max_mismatches:
            hits.append(AnchorHit(start, mm, tuple(mm_pos), tuple(mm_qual)))
    return hits


def extract_orientation_tolerant(seq: str, qual: str, anchor5: str, anchor3: str, max5: int, max3: int, expected_lengths: set[int], orientation: str) -> list[TolerantExtraction]:
    hits5 = hamming_anchor_hits(seq, qual, anchor5, max5)
    hits3 = hamming_anchor_hits(seq, qual, anchor3, max3)
    out: list[TolerantExtraction] = []
    invalid_lengths: list[int] = []
    for h5 in hits5:
        coding_start = h5.start + len(anchor5)
        for h3 in hits3:
            if h3.start < coding_start:
                continue
            insert_len = h3.start - coding_start
            if insert_len not in expected_lengths:
                invalid_lengths.append(insert_len)
                continue
            out.append(TolerantExtraction(
                seq[coding_start:h3.start], qual[coding_start:h3.start], orientation,
                h5.mismatches, h3.mismatches, h5.positions, h3.positions,
                h5.qualities, h3.qualities, bool(h5.mismatches or h3.mismatches)
            ))
    if not out and invalid_lengths:
        out.append(TolerantExtraction("", "", orientation, 0, 0, (), (), (), (), False, "invalid_length_frame", tuple(invalid_lengths)))
    return out


def extract_read_tolerant(seq: str, qual: str, anchor5: str, anchor3: str, max5: int, max3: int, expected_lengths: set[int]) -> TolerantExtraction | None:
    seq = seq.upper()
    candidates = extract_orientation_tolerant(seq, qual, anchor5, anchor3, max5, max3, expected_lengths, "forward")
    rc_seq = base.reverse_complement(seq)
    rc_qual = qual[::-1]
    candidates.extend(extract_orientation_tolerant(rc_seq, rc_qual, anchor5, anchor3, max5, max3, expected_lengths, "reverse_complement"))
    if not candidates:
        return None
    # Prefer no candidate arbitrarily. Equivalent duplicate candidates are still ambiguous because placements/orientations differ.
    unique = {(x.coding, x.orientation, x.anchor5_mismatches, x.anchor3_mismatches, x.anchor5_positions, x.anchor3_positions) for x in candidates}
    if len(unique) > 1:
        return TolerantExtraction("", "", "ambiguous", 0, 0, (), (), (), (), False, "multiple_anchor_candidates")
    return candidates[0]


def classify_tolerant(ext: TolerantExtraction | None, min_base_quality: int, min_mean_quality: float | None, max_n: int, seq_to_variant: dict[str, str], seq_to_control: dict[str, str]) -> tuple[str, str | None, str | None]:
    if ext is None:
        return "missing_flank", None, None
    if ext.reason == "invalid_length_frame":
        return "invalid_length_frame", None, None
    if ext.reason:
        return "ambiguous", None, None
    coding = ext.coding.upper()
    if len(coding) % 3:
        return "invalid_length_frame", coding, None
    quals = base.phred_scores(ext.coding_qual)
    if coding.count("N") > max_n or (quals and min(quals) < min_base_quality):
        return "low_quality", coding, None
    if min_mean_quality is not None and quals and statistics.fmean(quals) < min_mean_quality:
        return "low_quality", coding, None
    if coding in seq_to_variant:
        return "mapped_nnk", coding, seq_to_variant[coding]
    if coding in seq_to_control:
        return "mapped_control", coding, seq_to_control[coding]
    return "unexpected", coding, None


def fingerprint(sample: base.Sample, data_dir: Path, params: dict[str, Any]) -> dict[str, Any]:
    fp = base.checkpoint_fingerprint(sample, data_dir, params)
    fp.update({
        "pipeline_version": PIPELINE_VERSION,
        "max_5prime_anchor_mismatches": params["max_5prime_anchor_mismatches"],
        "max_3prime_anchor_mismatches": params["max_3prime_anchor_mismatches"],
        "enrich2_generation": False,
    })
    return fp


def process_sample_worker(args: tuple[dict[str, Any], str, dict[str, Any]]) -> dict[str, Any]:
    sample_dict, data_dir_s, params = args
    sample = base.Sample(**sample_dict)
    data_dir = Path(data_dir_s)
    path = data_dir / sample.fastq_filename
    total = 0; cats = Counter(); orient = Counter(); read_lengths = Counter(); dna_counts = Counter(); ctrl_counts = Counter(); unexpected = Counter()
    mismatch_counts = Counter(); mismatch_quals = Counter(); transition = Counter(); rescued = Counter(); rescued_by_mismatch = Counter(); len_counts = Counter(); rejected_len_counts = Counter(); flags=[]
    baseline_seq_to_variant = params["seq_to_variant"]; baseline_seq_to_control = params["seq_to_control"]
    max_reads = params.get("max_reads_per_file")
    for rec_no, h, seq, plus, qual, err in base.iter_fastq(path):
        if max_reads is not None and total >= max_reads:
            break
        total += 1; read_lengths[len(seq)] += 1
        if err:
            cats["malformed"] += 1; transition[("malformed","malformed")] += 1; continue
        exact_ext = base.extract_read(seq, qual, params["anchor5"], params["anchor3"])
        bcat, _, _ = base.classify_extracted(exact_ext, params["min_base_quality"], params.get("min_mean_quality"), params["max_n"], set(params["expected_lengths"]), baseline_seq_to_variant, baseline_seq_to_control)
        ext = extract_read_tolerant(seq, qual, params["anchor5"], params["anchor3"], params["max_5prime_anchor_mismatches"], params["max_3prime_anchor_mismatches"], set(params["expected_lengths"]))
        cat, coding, ref = classify_tolerant(ext, params["min_base_quality"], params.get("min_mean_quality"), params["max_n"], baseline_seq_to_variant, baseline_seq_to_control)
        cats[cat] += 1; transition[(bcat,cat)] += 1
        if ext and not ext.reason:
            orient[ext.orientation] += 1
            len_counts[len(ext.coding)] += 1
            mismatch_counts[(ext.anchor5_mismatches, ext.anchor3_mismatches)] += 1
            for q in ext.anchor5_qualities: mismatch_quals[("5prime", q)] += 1
            for q in ext.anchor3_qualities: mismatch_quals[("3prime", q)] += 1
            if ext.tolerant and cat in {"mapped_nnk","mapped_control"}:
                rescued[cat] += 1
                rescued_by_mismatch[(ext.anchor5_mismatches, ext.anchor3_mismatches, cat)] += 1
        if cat == "invalid_length_frame" and ext and ext.reason == "invalid_length_frame":
            unique_lengths = sorted(set(ext.invalid_insert_lengths))
            key = str(unique_lengths[0]) if len(unique_lengths) == 1 else "multiple"
            rejected_len_counts[key] += 1
        if cat == "mapped_nnk" and ref:
            dna_counts[ref] += 1
        elif cat == "mapped_control" and ref:
            ctrl_counts[ref] += 1
        elif cat == "unexpected" and coding:
            unexpected[coding] += 1
    if sum(cats[c] for c in base.READ_CATEGORIES) != total:
        flags.append("FAIL: count conservation")
    return {
        "sample": sample.__dict__, "file_size": path.stat().st_size, "total_reads": total,
        "category_counts": dict(cats), "orientation_counts": dict(orient), "read_lengths": dict(read_lengths),
        "dna_counts": dict(dna_counts), "control_counts": dict(ctrl_counts), "unexpected": dict(unexpected),
        "anchor_mismatch_counts": {f"{k[0]},{k[1]}": v for k,v in mismatch_counts.items()},
        "anchor_mismatch_quality_counts": {f"{k[0]},{k[1]}": v for k,v in mismatch_quals.items()},
        "transition_counts": {f"{k[0]}->{k[1]}": v for k,v in transition.items()},
        "rescued_counts": dict(rescued),
        "rescued_anchor_mismatch_counts": {f"{k[0]},{k[1]},{k[2]}": v for k,v in rescued_by_mismatch.items()},
        "insert_length_counts": dict(len_counts),
        "rejected_insert_length_counts": dict(rejected_len_counts),
        "fingerprint": fingerprint(sample, data_dir, params), "flags": flags,
    }


def sample_meta(sample: base.Sample) -> dict[str, Any]:
    return {"fastq_filename": sample.fastq_filename, "sample_id": sample.sample_id, "replicate": sample.replicate, "bait": sample.bait, "time_hours": sample.time_hours, "is_common_input": sample.is_common_input}


